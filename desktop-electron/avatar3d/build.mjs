// Builds `kai-avatar3d.js` — the classic script the app loads.
//
// The app has no bundler at runtime (every file is a plain `<script src>` under a
// strict CSP), and the character library imports `three` and two of its addons, so
// the bundle is built once and committed, exactly like `kai-character-engine.js`.
//
//   cd <repo>
//   npm run build:avatar        # or: node avatar3d/build.mjs
//
// Requirements: `esbuild` and `three` resolvable from the repo or from ESBUILD_DIR /
// NODE_PATH (the build is not part of the shipped app, so they are not dependencies
// of it).
import { createRequire } from 'node:module';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const outfile = join(repo, 'kai-avatar3d.js');
const scratch = process.env.KAI_AVATAR_BUILD_DIR || 'C:/tmp/kai-avatar-build';

const ROOTS = [repo, scratch, process.env.KAI_AVATAR_BUILD_DIR].filter(Boolean);

/** Resolve a package from the repo first, then from the external build directory. */
function resolveFromRoots(specifier) {
  for (const root of ROOTS) {
    try {
      return createRequire(join(root, 'package.json')).resolve(specifier);
    } catch {
      // Try the next root.
    }
  }
  return null;
}

/** Walks up from a package entry point to the folder whose package.json has `name`. */
function packageRoot(specifier, name) {
  for (const root of ROOTS) {
    try {
      let dir = dirname(createRequire(join(root, 'package.json')).resolve(specifier));
      while (dir !== dirname(dir)) {
        const manifest = join(dir, 'package.json');
        if (existsSync(manifest)) {
          try {
            if (JSON.parse(readFileSync(manifest, 'utf8')).name === name) return dir;
          } catch {
            // A malformed manifest higher up is not the package.
          }
        }
        dir = dirname(dir);
      }
    } catch {
      // Try the next root.
    }
  }
  return null;
}

const threeRoot = packageRoot('three', 'three');
if (!threeRoot) {
  console.error('three is not installed where this build can see it. Run: npm i three@0.186.1 in', scratch);
  process.exit(1);
}

const esbuildPath = resolveFromRoots('esbuild');
if (!esbuildPath) {
  console.error('esbuild is not installed where this build can see it. Run: npm i esbuild in', scratch);
  process.exit(1);
}
const { build } = await import(pathToFileURL(esbuildPath).href);

const result = await build({
  entryPoints: [join(here, 'src', 'index.js')],
  outfile,
  bundle: true,
  metafile: true,
  format: 'iife',
  target: ['chrome120'],
  minify: true,
  legalComments: 'inline',
  banner: {
    js: [
      '/* KAI3D — KAI’s 3D character, bundled for a page with no bundler.',
      ' *',
      ' * Generated by `avatar3d/build.mjs` from `avatar3d/src/`. Source of truth:',
      ' *   • avatar3d/src/blobCreature.js, furSystem.js, furShaders.js, gpuPhysics.js,',
      ' *     kaiState.js, stateIndicators.js — the supplied KAI 3D character library,',
      ' *     copied verbatim (no edits);',
      ' *   • avatar3d/src/character-config.js, state-bridge.js, stage.js, element.js,',
      ' *     index.js — the KAI integration written for this app.',
      ' *',
      ' * Regenerate with `npm run build:avatar`. Do not hand-edit this file.',
      ' */',
    ].join('\n'),
  },
  alias: {
    // Resolve the three addons through the same package the sources import.
    three: threeRoot,
  },
  logLevel: 'info',
});

if (result.errors.length) process.exit(1);
console.log(`kai-avatar3d.js written (${Math.round(statSync(outfile).size / 1024)} KiB)`);
